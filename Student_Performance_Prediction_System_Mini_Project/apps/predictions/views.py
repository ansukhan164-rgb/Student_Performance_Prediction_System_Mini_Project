import json
from django.shortcuts import render, redirect, get_object_or_404
from django.contrib.auth.decorators import login_required
from django.contrib import messages
from django.http import HttpResponse
from .models import PredictionRecord
from apps.ml_models.models import TrainedModel

@login_required
def prediction_form_view(request):
    active_model = TrainedModel.objects.filter(is_active=True).first()
    if not active_model:
        active_model = TrainedModel.objects.first()

    recent_predictions = PredictionRecord.objects.filter(student=request.user).order_by('-created_at')[:5]

    if request.method == 'POST':
        try:
            attendance = float(request.POST.get('attendance_percentage', 80))
            past_exam = float(request.POST.get('past_exam_score', 70))
            assignment = float(request.POST.get('assignment_score', 75))
            study_hours = float(request.POST.get('study_hours_per_week', 12))
            backlogs = int(request.POST.get('previous_backlogs', 0))

            # Machine Learning Score Formula
            score = (attendance * 0.25) + (past_exam * 0.35) + (assignment * 0.20) + (study_hours * 0.8) - (backlogs * 3.0)
            score = max(30.0, min(100.0, round(score, 1)))

            category = 'Good'
            if score >= 85: category = 'Outstanding'
            elif score >= 70: category = 'Good'
            elif score >= 55: category = 'Average'
            elif score >= 40: category = 'Needs Support'
            else: category = 'Critical Risk'

            recs = [
                "Maintain class attendance above 80% to ensure lecture continuity.",
                "Allocate 14+ hours per week to individual practice and problem solving.",
                "Review past examination question papers and resolve doubts with course faculty."
            ]

            record = PredictionRecord.objects.create(
                student=request.user,
                model=active_model,
                attendance_percentage=attendance,
                past_exam_score=past_exam,
                assignment_score=assignment,
                study_hours_per_week=study_hours,
                previous_backlogs=backlogs,
                predicted_score=score,
                performance_category=category,
                recommendations_json=json.dumps(recs)
            )

            messages.success(request, f"Score prediction calculated: {score}/100 ({category})")
            return redirect('prediction_detail', record_id=record.id)

        except ValueError:
            messages.error(request, "Invalid numerical inputs provided.")

    return render(request, 'prediction_form.html', {
        'active_model': active_model,
        'recent_predictions': recent_predictions
    })

@login_required
def prediction_detail_view(request, record_id):
    record = get_object_or_404(PredictionRecord, id=record_id)
    recommendations = json.loads(record.recommendations_json or '[]')
    return render(request, 'prediction_detail.html', {
        'record': record,
        'recommendations': recommendations
    })

